def setPWCSprite(eventID)
  prev = pbGet(37)
  if pbGet(36) == 12
    id = 999
  elsif pbGet(36) < 12 and pbGet(36) >= 10
    loop do
      id = rand(131, 144)
      break if !prev.include?(id)
    end
  else
    loop do
      id = rand(1, 130)
      break if !prev.include?(id)
    end
  end
  prev.append(id)
  pbSet(GCVariables::TRAINER_RANDOMIZER, id)
  id = getPWCTrainer(id)[2]
  id = "trchar" + id if FileTest.image_exist?("Graphics/Characters/trchar" + id)
  event = get_character(eventID)
  event.character_name = id
  # Ensures that Liza shows up too!
  return if id != "trchar096"
  event2 = get_character(24)
  event2.moveto(event.x + 1, event.y)
end

def pbPWCBattle(fieldeff=0)
  trainer = getPWCTrainer(pbGet(GCVariables::TRAINER_RANDOMIZER))
  pbMessage(_INTL(trainer[3]))
  setBattleRule("canlose")
  setBattleRule("setstyle")
  setBattleRule("itemlimit", 1)
  case rand(1, 3)
  when 3
    setBattleRule("triple")
  when 2
    setBattleRule("double") # default is single
  end
  case fieldeff
  when 1
    setBattleRule("fieldeffect", :Fire)
  when 2
    setBattleRule("fieldeffect", :Water)
  when 3
    setBattleRule("fieldeffect", :Rock)
  when 4
    setBattleRule("fieldeffect", :Ice)
  when 5
    setBattleRule("fieldeffect", :Electric)
  when 6
    setBattleRule("fieldeffect", :Psychic)
  when 7
    setBattleRule("fieldeffect", :Grass)
  when 8
    setBattleRule("fieldeffect", :Mist) # default is none
  end
  case trainer[0]
  when :RIVAL3  # Paul
    vers = 11
  when :POKEMONCOORDINATOR_Dawn
    vers = 8
  when :COOLTRAINER_M
    vers = 6 if trainer[1] == "Trip"
  when :POKEMONTRAINER_Alain1
    vers = 6
  when :GENTLEMAN # Nando
    vers = 5
  else
    vers = 3
  end
  if pbTrainerBattle(trainer[0], trainer[1] ,nil, false, vers)
    pbMessage(_INTL(trainer[4]))
    pbSet(36, pbGet(36) + 1)
    return true
  else
    pbMessage(_INTL(trainer[-1]))
    return false
  end
end
