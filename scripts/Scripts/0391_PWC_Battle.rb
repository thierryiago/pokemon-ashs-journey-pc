# Custom set of rules for the anime PWC
class PWCRestriction
  def isValid?(pkmn)
    return false if !pkmn || pkmn.egg?
    # Species with disadvantageous abilities are not banned
    pkmn.species_data.abilities.each do |a|
      return true if [:TRUANT, :SLOWSTART].include?(a)
    end
    # Allow Psuedo-Legendaries
    return true if [:DRAGONITE, :TYRANITAR, :SALAMENCE,
                    :METAGROSS, :GARCHOMP, :HYDREIGON,
                    :GOODRA, :KOMMOO, :DRAGAPULT].include?(pkmn.species)
    # Certain named species are banned
    return false if [:WYNAUT, :WOBBUFFET, :URSHIFU].include?(pkmn.species)
    # Species with total base stat 600 or more are banned
    # (Legendaries and Mythicals, but not mons with megas)
    bst = 0
    pkmn.baseStats.each_value { |s| bst += s }
    return false if bst >= 600
    # Is valid
    return true
  end
end

def pbPWCRules
  ret = PokemonChallengeRules.new
  ret.addPokemonRule(PWCRestriction.new)
  ret.addTeamRule(SpeciesClause.new)
  ret.addTeamRule(ItemClause.new)
  ret.addBattleRule(SoulDewBattleClause.new)
  ret.ruleset.setNumber(6)
  return ret
end

